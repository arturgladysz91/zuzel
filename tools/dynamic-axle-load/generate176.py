"""Generate a research-only #172 world with an isolated contact dispatch."""
import argparse
from pathlib import Path

TOOL = Path(__file__).resolve().parent
SOURCE = TOOL.parent/'three-lap-global-planning/NativeWorld172.Generated.cs'


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f'Frozen world hook mismatch: {old}')
    return text.replace(old, new)


def content():
    text = SOURCE.read_text(encoding='utf-8')
    text = once(text, 'using Limits149;', 'using Limits149;\nusing Speed148;')
    text = once(text, '    readonly double safetyFrom,stopReference,postSeconds;',
                '    readonly double heightMeters, transferFrom;\n'
                '    readonly double[] acceptedAx;\n'
                '    public double AcceptedAx => acceptedAx[0];\n'
                '    readonly double safetyFrom,stopReference,postSeconds;')
    text = once(text, 'double postSeconds=0){',
                'double postSeconds=0,double heightMeters=0,double transferFrom=0){\n'
                '        if(heightMeters is not (0 or .35 or .55) || !double.IsFinite(transferFrom) || transferFrom<0 || separated)\n'
                '            throw new ArgumentException("Only the declared axle-load treatments are permitted.");\n'
                '        this.heightMeters=heightMeters;this.transferFrom=transferFrom;')
    text = once(text, '        shafts=specs.Select',
                '        acceptedAx=new double[specs.Length];\n        shafts=specs.Select')
    text = once(text, '        =>separated?Contact149.Forces',
                '        =>heightMeters>0&&time>=transferFrom-1e-8\n'
                '            ?AxleContact176.Forces(v,spec,frame,surface,p,time,mass,wheel,state,seconds,\n'
                '                steeringOverride!.Value,powertrain!,releaseAt,heightMeters,acceptedAx[v.Id-1])\n'
                '            :separated?Contact149.Forces')
    text = once(text, '                if(specs[i].SpeedMetersPerSecond==0&&time<',
                '                acceptedAx[i]=FullDrive169.Contact169.Acceleration(before[i],views[i],(float)dt);\n'
                '                if(specs[i].SpeedMetersPerSecond==0&&time<')
    text = once(text, '            physics.Step((float)dt,parameters.SolverSubsteps);',
                '            bool usingTransfer=heightMeters>0&&time>=transferFrom-1e-8;\n'
                '            physics.Step((float)dt,parameters.SolverSubsteps);')
    text = once(text, '            for(int i=0;i<specs.Length;i++){wheels[i].Commit();steering[i].Commit();shafts[i].Commit();}',
                '            for(int i=0;i<specs.Length;i++){\n'
                '                // Contact169 returns a detached solved step. Commit that step once, as in #169.\n'
                '                if(usingTransfer){\n'
                '                    wheels[i]=ForecastFork148.Wheel(powers[i].Wheel.AfterOmega,wheels[i].Parameters);\n'
                '                    steering[i]=new TwoContactBikeState(forces[i].SteeringAfter);\n'
                '                }else{wheels[i].Commit();steering[i].Commit();}\n'
                '                shafts[i].Commit();\n'
                '                if(Math.Abs(wheels[i].AngularVelocityRadPerSecond-powers[i].Wheel.AfterOmega)>1e-8 ||\n'
                '                   steering[i].SteeringRadians!=forces[i].SteeringAfter ||\n'
                '                   shafts[i].Omega!=powers[i].AfterOmega)\n'
                '                    throw new InvalidOperationException("Contact result was not committed to all three states.");\n'
                '            }')
    text = once(text, '                if(powers[i].ClutchHeatJoules<-.001||wheels[i].Prepared.LongitudinalLossJoules<-.001||wheels[i].Prepared.RearUtilization>1.000001)',
                '                var appliedWheel=usingTransfer?power.Wheel:wheels[i].Prepared;\n'
                '                if(powers[i].ClutchHeatJoules<-.001||appliedWheel.LongitudinalLossJoules<-.001||appliedWheel.RearUtilization>1.000001)')
    text = once(text, '                if(reason is not null&&failure is null)',
                '                if(heightMeters>0&&time>transferFrom+1e-8)\n'
                '                    reason ??= AxleContact176.InvalidLoad(acceptedAx[i],heightMeters);\n'
                '                if(reason is not null&&failure is null)')
    return '// Generated by generate176.py. Frozen Box2D and original safety gates.\n' + text


def files():
    yield TOOL/'NativeWorld176.Generated.cs', content()
    for name in ('CyclicController172.cs','CyclicExit172.Generated.cs',
                 'Policy172.Generated.cs','Tracker172.Generated.cs'):
        original=(SOURCE.parent/name).read_text(encoding='utf-8')
        modified=once(original,'PredictorA153.Predict(', 'ForecastDispatch176.Predict(')
        yield TOOL/('Dispatch176.'+name), '// Generated by generate176.py. K4 policy unchanged.\n'+modified
    original=(TOOL.parent/'full-drive-stability/Predictor169.Generated.cs').read_text(encoding='utf-8')
    text=once(original,'class Predictor169','class Predictor176')
    text=once(text,'double stepSeconds=.01)','double stepSeconds=.01,Efficient152.Boundary152? fastBoundary=null)')
    text=once(text,'var boundary = new RacingLineGeometry(frame);',
              'var boundary = fastBoundary is null ? new RacingLineGeometry(frame) : null;')
    text=once(text,'var gap = boundary.Clearance(v);','var gap = fastBoundary?.Clearance(v) ?? boundary!.Clearance(v);')
    text=once(text,'if(useVariant)return Contact169.Forces(v,spec,frame,surface,p,time,mass,wheel,steering,dt,\n'
                   '                    active.SteeringRadians,shaft,reaction,variant,acceptedAx);',
                   'if(useVariant)return Cyclic172.AxleContact176.Forces(v,spec,frame,surface,p,time,mass,wheel,steering,dt,\n'
                   '                    active.SteeringRadians,shaft,reaction,variant.HeightMeters,acceptedAx);')
    yield TOOL/'Predictor176.Generated.cs', '// Generated by generate176.py from the #169 causal model.\n'+text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    check = parser.parse_args().check
    for target,text in files():
        if check:
            assert target.read_text(encoding='utf-8') == text, target
        else:
            target.write_text(text,encoding='utf-8',newline='\n')
