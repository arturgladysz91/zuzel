"""Generate an isolated, auditable diagnostic copy; never edit the inherited physics.
--check proves checked-in copies contain only these declared substitutions.
"""
import re
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'tools/shared-world-speedway'
DEST=SOURCE/'PhysicsValidation139'
DEST.mkdir(exist_ok=True)

def replace(source,old,new,count=1):
    assert source.count(old)==count,(old,source.count(old),count)
    return source.replace(old,new)

contact=(SOURCE/'TwoContactBikeDynamics.cs').read_text(encoding='utf-8')
contact=contact[contact.index('public static class TwoContactBikeDynamics'):]
contact='// Generated by tools/motorcycle-physics-validation/generate-sandbox.py; diagnostic only.\nusing System.Numerics;\nusing CoreSim;\nusing CoreSim.PhysicalSpace;\nnamespace SharedWorldSpeedway;\n'+contact
contact=contact.replace('public static class TwoContactBikeDynamics','public static class DiagnosticContact139')
contact=replace(contact,'Action<TwoContactObservation>? observeContacts=null,float? inertia=null)',
    'Action<TwoContactObservation>? observeContacts=null,float? inertia=null,PhysicsVariant139? variant=null)')
contact=replace(contact,'    {\n        if(!p.EnableTwoContactBikeDynamics',
    '    {\n        variant??=PhysicsVariant139.Original;\n        if(variant==PhysicsVariant139.Original)return TwoContactBikeDynamics.Forces(v,spec,frame,surface,p,time,mass,wheel,state,seconds,path,steeringOverride,observe,observeContacts,inertia);\n        if(!p.EnableTwoContactBikeDynamics')
contact=replace(contact,'var geometry=p.TwoContactBike??TwoContactBikeParameters.Default;',
    'var geometry=(p.TwoContactBike??TwoContactBikeParameters.Default) with{FrontAxleFromComMeters=(float)variant.FrontArm,RearAxleFromComMeters=(float)variant.RearArm};')
contact=replace(contact,'var ahead=Math.Max(.1,frame.ReferenceSpeed(road,speed)*2*p.YawResponseSeconds);',
    'if(variant.FrontFraction is{} split){var normal=mass*LoadBasedTyreGrip.GravityMetersPerSecondSquared;tyreLoads=new(tyreLoads!.EffectiveFrictionCoefficient,normal*split,normal*(1-split));}\n        var ahead=Math.Max(.1,frame.ReferenceSpeed(road,speed)*2*p.YawResponseSeconds);')
contact=replace(contact,'new(delta){AxleLoad=load},seconds,path,delta);','new(delta){AxleLoad=load},seconds,path,delta,variant:variant);')
contact=replace(contact,'SlipCoupledDynamics.VelocityScaleSquared(uf,budget/mass));',
    '(float)(SlipCoupledDynamics.VelocityScaleSquared(uf,budget/mass)*variant.FrontScaleSquared));')
contact=replace(contact,'var wp=wheel.Parameters;','var wp=wheel.Parameters with{LongitudinalSlipStiffnessRatio=wheel.Parameters.LongitudinalSlipStiffnessRatio*variant.RearLongScale,MinimumContactRelaxationSeconds=wheel.Parameters.MinimumContactRelaxationSeconds*variant.ContactRegularization};')

adapter=(SOURCE/'ContactAdapter.cs').read_text(encoding='utf-8')
adapter=re.sub(r'\bContactAdapter\b','ContactAdapter139',adapter)
adapter=replace(adapter,'TwoContactInitialState? twoContactInitial=null)','TwoContactInitialState? twoContactInitial=null,double inertiaScale=1)')
adapter=replace(adapter,'var inertia = natural.rotationalInertia / natural.mass * Masses[i];',
    'var inertia = natural.rotationalInertia / natural.mass * Masses[i];\n            if(inertiaScale!=1)inertia*=(float)inertiaScale;')

world=(SOURCE/'WorldRunner.cs').read_text(encoding='utf-8')
world=re.sub(r'\bWorldRunner\b','PhysicsWorld139',world)
world=re.sub(r'\bContactAdapter\b','ContactAdapter139',world)
world=replace(world,'private const double CurvatureEventResolutionSeconds',
    'private readonly PhysicsVariant139 validationVariant;\n    private const double CurvatureEventResolutionSeconds')
world=replace(world,'FreeRacingPolicy? freeRacingPolicy=null, FreeLearningPolicy? freeLearningPolicy=null)',
    'FreeRacingPolicy? freeRacingPolicy=null, FreeLearningPolicy? freeLearningPolicy=null,PhysicsVariant139? validationVariant=null)')
world=replace(world,'        this.diagnostics = diagnostics;',
    '        this.validationVariant=validationVariant??PhysicsVariant139.Original;\n        this.validationVariant.Validate();\n        this.diagnostics = diagnostics;')
world=replace(world,'physics = new(specs, Frame, Parameters,twoContactInitial);',
    'physics = new(specs, Frame, Parameters,twoContactInitial,this.validationVariant.InertiaScale);')
world=world.replace('TwoContactBikeDynamics.Forces(','DiagnosticContact139.Forces(')
world=replace(world,'diagnostics?.TwoContact,physics.Inertias[i]);','diagnostics?.TwoContact,physics.Inertias[i],validationVariant);')
world=replace(world,'inertia:physics.Inertias[i]);','inertia:physics.Inertias[i],variant:validationVariant);')

native=(SOURCE/'CausalYawNative137.cs').read_text(encoding='utf-8')
native=native.replace('public static class CausalYawNative137','public static class PhysicsNative139')
native=replace(native,'bool extendAfterSecondStraight=false)',
    'bool extendAfterSecondStraight=false,PhysicsVariant139? validationVariant=null)')
native=replace(native,'new WorldRunner(','new PhysicsWorld139(')
native=replace(native,'diagnostics:new(){Force=f=>before=f.Rider,TwoContact=o=>force=o.Forces,RearWheel=o=>wheel=o.Step});',
    'diagnostics:new(){Force=f=>before=f.Rider,TwoContact=o=>force=o.Forces,RearWheel=o=>wheel=o.Step},validationVariant:validationVariant);')

for name,text in {'DiagnosticContact139.cs':contact,'ContactAdapter139.cs':adapter,'PhysicsWorld139.cs':world,'PhysicsNative139.cs':native}.items():
    path=DEST/name
    if '--check'in sys.argv:
        assert path.read_text(encoding='utf-8').replace('\r\n','\n')==text.replace('\r\n','\n'),name
    else:path.write_text(text,encoding='utf-8',newline='\n')
print('Sandbox substitutions verified'if '--check'in sys.argv else 'Generated four isolated diagnostic sources')
