"""Instrument the frozen #144 collector without changing its historical sources.

Only a chooser callback is inserted. ContactAdapter/Box2D, clock, forces,
actuator, delayed queue, all safety guards and finish accounting are identical.
"""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[2]

def generated():
    s=(ROOT/'tools/shared-world-speedway/StandingStart144/StandingWorld144.cs').read_text(encoding='utf-8')
    s=s.replace('StandingWorld144','DiagnosticWorld145')
    # Reuse the public #144 records from the referenced assembly.
    a=s.index('public sealed record StandingOptions144')
    b=s.index('/// <summary>Opt-in harness',a)
    s=s[:a]+s[b:]
    old='public Run144 Run(string name,string variant){'
    new='public Run144 Run(string name,string variant,Func<FreeRacingInput,CrankClutch144,RiderSpec,TrackFrame,TrackStateSnapshot,WorldParameters,float,float,string,Decision144>? chooser=null){'
    assert s.count(old)==1;s=s.replace(old,new)
    old='var choice=Policy144.Choose(Input(i),shafts[i],specs[i],frame,surface,parameters,physics.Masses[i],physics.Inertias[i],variant);'
    new='var choice=chooser is null?Policy144.Choose(Input(i),shafts[i],specs[i],frame,surface,parameters,physics.Masses[i],physics.Inertias[i],variant):chooser(Input(i),shafts[i].Copy(),specs[i],frame,surface,parameters,physics.Masses[i],physics.Inertias[i],variant);'
    assert s.count(old)==1;s=s.replace(old,new)
    return '// Generated by generate.py from frozen #144; do not edit manually.\n'+s

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    target=Path(__file__).with_name('DiagnosticWorld145.cs');s=generated()
    if args.check: assert target.read_text(encoding='utf-8')==s,'Generated collector differs'
    else: target.write_text(s,encoding='utf-8',newline='\n')
