"""Produce the isolated #166 runner with unchanged Box2D steps and contact laws."""
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
old = (root / "tools/line-throttle-physics/NativeWorld156.Generated.cs").read_text()
source = old.replace("namespace LineThrottle156;", "namespace LearnedCorner166;")
source = source.replace("NativeWorld156", "NativeWorld166")
source = source.replace("readonly RiderSpec[] specs;", "readonly RacingLineGeometry boundary;\n    readonly RiderSpec[] specs;")
source = source.replace("frame=diagnosticFrame??Frame();parameters=", "frame=diagnosticFrame??Frame();boundary=new(frame);parameters=")
source = source.replace("new RacingLineGeometry(frame).Clearance(views[i])", "boundary.Clearance(views[i])")
source = source.replace("var boundary=new RacingLineGeometry(frame);", "")
source = source.replace("readonly double safetyFrom,stopReference;", "readonly double safetyFrom,stopReference,postSeconds;")
source = source.replace("double? stopReference=null)", "double? stopReference=null,double postSeconds=0)")
source = source.replace("this.safetyFrom=safetyFrom;", "this.postSeconds=postSeconds;this.safetyFrom=safetyFrom;")
source = source.replace("for(int i=0;i<specs.Length;i++)Sample(i);",
                        "double? postEnd=null;\n        for(int i=0;i<specs.Length;i++)Sample(i);")
source = source.replace("views[0].TotalReferenceMeters<this.stopReference",
                        "(views[0].TotalReferenceMeters<this.stopReference || postSeconds>0 && (postEnd is null || time<postEnd-1e-10))")
source = source.replace("// Activate every irrevocable queue before capturing the common accepted observation.",
                        """if(views[0].TotalReferenceMeters>=stopReference && postEnd is null)
                postEnd=time+postSeconds;
            // Activate every irrevocable queue before capturing the common accepted observation.""")
source = source.replace("var dt=Math.Min(nominal-time,options.MaximumSeconds-time);",
                        "var dt=Math.Min(nominal-time,Math.Min(options.MaximumSeconds,postEnd??double.PositiveInfinity)-time);")
source = source.replace("using SharedWorldSpeedway;", "using SharedWorldSpeedway;\nusing Limits149;")
source = "// Generated by generate166.py from NativeWorld156. Caches the same read-only geometry and permits a bounded post-goal window.\n" + source
target = Path(__file__).with_name("NativeWorld166.Generated.cs")
if "--check" in sys.argv:
    assert target.read_text() == source
else:
    target.write_text(source, encoding="utf-8", newline="\n")
